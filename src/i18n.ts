export function quizResult(score: number, lang: Lang) {
  const max = QUIZ[lang].length * 2;
  const pct = Math.round((score / max) * 100);
  if (pct >= 80)
    return {
      level: lang === 'fr' ? 'Excellent' : 'Excellent',
      msg:
        lang === 'fr'
          ? 'Vos réflexes sont solides. Partagez ce quiz pour aider vos proches à se protéger.'
          : 'Your reflexes are solid. Share this quiz to help your loved ones stay safe.',
      color: 'var(--good)',
    };
  if (pct >= 50)
    return {
      level: lang === 'fr' ? 'Bien, mais perfectible' : 'Good, but improvable',
      msg:
        lang === 'fr'
          ? 'Vous avez de bonnes bases. Relisez les guides sur les points faibles pour monter en puissance.'
          : 'You have good basics. Review the guides on your weak spots to level up.',
      color: 'var(--warn)',
    };
  return {
    level: lang === 'fr' ? 'À renforcer' : 'Needs work',
    msg:
      lang === 'fr'
        ? 'C\'est normal : personne ne naît préparé. Commencez par le guide « Hameçonnage » et la checklist — 15 minutes suffisent pour changer la donne.'
        : 'That is normal: nobody is born prepared. Start with the "Phishing" guide and the checklist — 15 minutes can change everything.',
    color: 'var(--bad)',
  };
}

