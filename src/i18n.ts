  if (pct >= 80)
    return {
      level: lang === 'fr' ? 'Excellent' : 'Excellent',
      msg:
        lang === 'fr'
          ? 'Vos réflexes sont solides. Partagez ce quiz pour aider vos proches à se protéger.'
          : 'Your reflexes are solid. Share this quiz to help your loved ones stay safe.',
      color: 'var(--good)',
    };
  if (pct >= 50)
    return {
      level: lang === 'fr' ? 'Bien, mais perfectible' : 'Good, but improvable',
      msg:
        lang === 'fr'
          ? 'Vous avez de bonnes bases. Relisez les guides sur les points faibles pour monter en puissance.'
          : 'You have good basics. Review the guides on your weak spots to level up.',
      color: 'var(--warn)',
    };
